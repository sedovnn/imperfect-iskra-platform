    // же фразу, что читает человек. String(объект) дал бы «[object Object]» — ровно так
    // 13.08 потерялись восемь тезисов живого прогона, и проверка это пропустила.
    var flat = function (v) {
      return (Array.isArray(v) ? v : [v]).map(function (x) {
        if (x && typeof x === 'object' && (x.head != null || x.tail != null)) {
          return String(x.head || '') + (x.head && x.tail ? ' ' : '') + String(x.tail || '');
        }
        return String(x == null ? '' : x);
      }).join('\n');
    };
    return [
      flat(s.lead).split('{name}').join(name || ''),
      s.title ? s.title + ':' : '',
      // ⚠ titleLead ДОБАВЛЕН 26.08: 26.08 первый пункт rules вышел из списка и стал лидом
      // страницы — и вместе с этим ПЕРЕСТАЛ уходить модели, потому что здесь его никто не
      // перечислял. Дыра моя, поймана при следующей же правке этого места: модель
      // лишилась фразы «ассессмент состоит из семи этапов», которую человек читает.
      flat(s.titleLead),
      flat(s.rules),
      flat(s.howItWorks),
      s.note || ''
    ].filter(Boolean).join('\n\n');
