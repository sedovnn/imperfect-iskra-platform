  // в маршруте — движок и харнесс решают по одному и тому же правилу, показывать
  // ли их. Ключи шагов строковые: перестановка сцен меняет sha сценария, а не
  // молча сдвигает индексы (режим отказа 25).
  S.route = function () {
    var out = [];
    S.scenes.forEach(function (sc, si) {
      sc.acts.forEach(function (act, ai) {
        out.push({ act: act, scene: sc, sceneIx: si, actIx: ai, stepId: sc.id + '/' + act.id });
      });
    });
    return out;
  };

  // Все окна маршрута в порядке предъявления — источник и для полей Answers,
  // и для панели «Мои ответы», и для свода дня.
  // ⚠ МЕХАНИКИ ЗДЕСЬ ТОЖЕ. С маршрута v4.4.f основной измеряемый текст живёт не в
  // свободных окнах, а внутри механик (тезисы и связки, варианты, критерии списка,
  // строка печати, карточки будущего, цель, четыре поля письма) — свободных окон
  // осталось пять из двенадцати шагов. Пока здесь стояло только kind==='window',
  // семь флагов элиситации из девяти не доезжали до протокола вообще: судья
  // читал бы вызванные признаки как принесённые сами и завышал уровень.
  // Поле .mech отличает механику от окна — потребители (панель «Мои ответы»,
  // поля Answers, вход судьи) обязаны на него смотреть, а не гадать по save.
  S.windows = function () {
    var out = [];
    S.scenes.forEach(function (sc) {
      sc.acts.forEach(function (a) {
        if (a.kind !== 'window' && a.kind !== 'mechanic') return;
        out.push({
          scene: sc, act: a, save: a.save, label: a.label || a.task || '',
          elicited: a.elicited || [], conditional: !!a.when,
          mech: a.kind === 'mechanic' ? a.mech : null
        });
      });
    });
    return out;
  };

  // Флаги элиситации по полю ответа: {q1:['ak2_conclusion_asked'], ...}
  S.elicitedMap = function () {
    var m = {};
    S.windows().forEach(function (w) { if (w.elicited.length) m[w.save] = w.elicited.slice(); });
    return m;
  };

  window.imp.scenes = S;
