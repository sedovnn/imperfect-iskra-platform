  // ⚠ ВОПРОС ОСТАЁТСЯ НА ЭКРАНЕ (14.08, решение владельца). Прежде в свёртку уезжало
  // ВСЁ сказанное, и участник писал ответ, видя только названия полей: «Ваши варианты /
