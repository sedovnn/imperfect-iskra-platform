  function subst(text) {
    var t = String(text || '');
    if (t.indexOf('{name}') >= 0) {
      var nm = pname();
      // Имени может не быть: старая сессия, вход по номеру без самозаписи, пустое
      // поле. Тогда убираем не подстановку, а всё обращение вместе с запятой —
      // иначе персонаж говорит «Спасибо, . Прочитал» и выглядит сломанным.
      t = nm ? t.split('{name}').join(nm)
             : t.replace(/,\s*\{name\}/g, '').replace(/\{name\}\s*,\s*/g, '').split('{name}').join('');
    }
    // {who} и {title} — хозяин самой дорогой по людям отказанной заявки и её
    // название. Подставляются только в сцене на выходе из офиса; если отказов нет,
    // сцена не играется вовсе (applies), и подставлять нечего.
    if (t.indexOf('{who}') >= 0 || t.indexOf('{title}') >= 0 || t.indexOf('{whoName}') >= 0) {
      // ⚠ БЫЛО refusedPick() — И ЭТО БЫЛ БАГ (поймано владельцем 19.08). refusedPick
      // отдаёт СЫРУЮ заявку из backlog.js: у неё есть who и title, но нет whoName.
      // `'{whoName}'.split('{whoName}').join(undefined)` даёт не пустую строку, а
      // запятую — join без разделителя ставит «,». Поэтому над репликой на выходе из
      // офиса висел кружок с запятой вместо имени. Вложенные кавычки в названии
      // заявки тоже не обрабатывались: в пузыре выходило «…блок «Маяка», а не…».
      // refusedParts готовит все три подстановки, для того и написан.
      var pk = refusedParts();
      // Готовые подстановки берём из backlog.js: там же, где правило выбора, лежит
      // и подготовка текста (вложенные кавычки в названии заявки). Своей обработки
      // здесь нет намеренно — иначе три харнесса разойдутся в мелочах.
      t = t.split('{whoName}').join(pk.whoName)
           .split('{who}').join(pk.who)
           .split('{title}').join(pk.title);
    }
    if (t.indexOf('{people}') >= 0 || t.indexOf('{money}') >= 0) {
      // ⚠ ЧИСЛА БЕРУТСЯ ИЗ НОВОГО СПИСКА (правка 09.08). Здесь стоял старый
      // totals(), который считает по state.picks — модели, которой на маршруте
      // v4.4.f больше нет. Поэтому Агеев говорил «Так. 0 человек — при пятистах»
      // ровно там, где участник вышел за рамку. Ветвление шага (applies) давно
      // считает по listSums(); теперь и реплика читает тот же счёт.
      var tt = listSums() || totals();
      t = t.split('{people}').join(String(tt.people)).split('{money}').join(num(tt.money));
    }
    // ⚠ {over} — НАЗЫВАЕТ ТОЛЬКО ТО, ЧТО ПРЕВЫШЕНО (правка владельца 19.08).
    // Реплика перебора зачитывала обе величины всегда, и Агеев говорил «21,5 — при
    // двадцати двух» там, где по деньгам участник как раз уложился: придирка к тому,
    // что в порядке. Теперь деньги упоминаются только при переборе по деньгам, люди —
    // только по людям, обе — если обе. Машинный факт того же сорта, что {people}/{money}:
    // не зависит ни от содержания ответа, ни от его длины, поэтому правило «текст пузыря
    // фиксирован» не нарушено — условие живёт здесь, а не в scenes.js.
    // ⚠ {futureRef} — КАК НАЗЫВАТЬ БУДУЩЕЕ, ПРО КОТОРОЕ СПРАШИВАЕТ ЛЕМЕХ
    // (правка владельца 19.08). Если участник написал одно будущее, «наиболее
    // вероятный вариант» звучит нелепо: выбирать было не из чего. Если несколько —
    // он его отметил, и вопрос идёт именно про отмеченный. Машинный факт того же
    // сорта, что {over}: зависит от числа заполненных карточек, а не от их текста.
    // ⚠ САМ РАСЧЁТ ЖИВЁТ В js/mech-fields.js (window.imp.subFacts). Здесь он был
    // написан только для экрана, и оба харнесса про эти подстановки не знали вовсе:
    // модель получала «У вас получилось {over}» с фигурными скобками там, где человек
    // читает названное превышение (сверка 21.08). Реплика с подстановкой — это вопрос,
    // на который отвечают; разойтись в нём значит спросить у модели другое.
    if (t.indexOf('{futureRef}') >= 0) {
      t = t.split('{futureRef}').join(window.imp.subFacts.futureRef(state.mech && state.mech.futures));
    }
    if (t.indexOf('{over}') >= 0) {
      t = t.split('{over}').join(window.imp.subFacts.over(listSums() || totals(), LIM, plural, num));
    }
    // ⚠ {forcedTitle} и {forcedCost} — заявка, на которой настаивает правление (26.08).
    // Выбор живёт в js/backlog.js рядом с refusedOwner: он тоже читает бэклог и отказы,
    // и разводить их по файлам значит завести две разные правды про одни и те же данные.
    if (t.indexOf('{forcedTitle}') >= 0 || t.indexOf('{forcedCost}') >= 0) {
      var fp = window.imp.forcedParts(refusedIds(), listSums() || totals(), LIM, num, plural, isDemo);
      t = t.split('{forcedTitle}').join(fp.title).split('{forcedCost}').join(fp.cost);
    }
    return t;
  }

  // Две позиции, про которые Агеев спрашивает сам: самые дорогие по людям из
  // отложенных, при равенстве — с меньшим номером. Правило детерминировано, а не
  // случайно, по двум причинам: случайность у разных участников давала бы разную
  // задачу, а харнесс модели обязан воспроизвести тот же выбор. Участнику правило
  // неизвестно — подготовить удобный ответ он не может.
  // ⚠ namedRefusals() УБРАНА 11.08 (решение владельца, Р4). Она выбирала две самые
  // дорогие по людям отложенные позиции для реплики Агеева «вы отложили №… и №…».
  // Реплики в маршруте больше нет, подстановок {drop1}/{drop2} ноль, флаг до судьи
  // не доезжал. Правило выбора и доводы, зачем вопрос заводили, сохранены в
  // СПЕК.md §4.5а — если его вернут, восстанавливать по описанию, а не по памяти.

  // Условный пузырь: реплика может опираться на поступок участника, а поступка
  // может не быть — тогда её нельзя произносить, иначе персонаж спрашивает про
  // пустое место. Единственное такое условие (needs:'refusals') снято 11.08 вместе
  // с вопросом про два отказа, и сейчас условий нет ни у одного пузыря. Функция
  // оставлена: место для них есть, а проверка стоит в одной точке.
  // ⚠ УСЛОВИЕ У ОТДЕЛЬНОГО ПУЗЫРЯ (правка 13.2). Понадобилось, когда в разговоре у выхода
  // одно слово стало зависеть от того, ОТЛОЖИЛ участник заявку или ОТКЛОНИЛ. Ветвление
  // актом стоило бы разрезания монолога на четыре акта с повторной подписью говорящего, а
  // ветвление в разметке запрещено правилом «ни одной реплики литералом». Условие пузыря —
  // та же машинерия applies(), что у актов: обе редакции текста остаются в js/scenes.js.
  // Пузырь без when/unless показывается всегда, как и раньше.
  function bubbleShown(b) { return applies(b); }

  // ── РЕПЛИКИ ПОЯВЛЯЮТСЯ ПО ОДНОЙ (решение владельца 07.08) ──
  // Разметка та же, добавляется только метка data-reveal; показывает их revealRun
  // ниже. Печати по буквам НЕТ — владелец снял её отдельно: имя собеседника и
  // ремарка появляются целиком вместе со своим первым пузырём.
  var revealTimer = null;
  // ⚠ ПАУЗА ЗАВИСИТ ОТ ДЛИНЫ РЕПЛИКИ (правка владельца 28.08). Была одна на всех — 620 мс,
  // — и реплика на 261 знак получала столько же, сколько «Всё, не отвлекаю»: на небольшом
  // окне длинную не успевали дочитать, её уводила следующая. Теперь база плюс время на
  // знак, с потолком: без потолка самая длинная реплика останавливала бы разговор на
  // несколько секунд, а это уже не темп, а ожидание.
  // Считаем по длине САМОГО УЗЛА, а не по данным сцены: узел может быть не пузырём —
  // очередь показа ведёт и поля ответа, и блоки верстака.
  var REVEAL_MS = 620;
  var REVEAL_PER_CHAR = 9;
  var REVEAL_MAX = 2400;
  function revealPause(node) {
    var n = ((node && node.textContent) || '').trim().length;
    return Math.min(REVEAL_MS + n * REVEAL_PER_CHAR, REVEAL_MAX);
  }
  // ⚠ ПАМЯТЬ ПОКАЗАННЫХ ПУЗЫРЕЙ. Без неё render() помечал реплики текущего шага
  // заново на КАЖДОЙ перерисовке, и после «Ответить» весь монолог проигрывался
  // сначала (поймано владельцем 07.08). Живёт в памяти страницы, а не в состоянии:
  // это не ответ и не место в маршруте, а факт «этот пузырь на экране уже был».
  // После перезагрузки страницы монолог текущего шага покажется по одному ещё раз —
  // и это правильнее, чем показать его сразу целиком.
  var shownBubbles = {};

  // Какой разговор был нарисован в прошлый раз. Нужен затем, чтобы прокрутка к
  // началу сцены случалась ОДИН раз — на входе в неё, а не на каждой перерисовке
  // внутри (см. конец render()). Живёт в памяти страницы: это не место в маршруте
  // и не ответ, а факт «этот разговор уже открыт».
  var lastSceneId = null;

  // Идёт по помеченным узлам в порядке разметки и снимает метку с каждого через
  // REVEAL_MS. По окончании зовёт done — там открывается рабочая область.
  // ⚠ ТРЕТИЙ АРГУМЕНТ clear — ТОЛЬКО ДЛЯ СВЕЖЕГО ШАГА (правка 28.08). Такт «сначала
  // освобождаем экран» (ниже) до 28.08 не срабатывал ВООБЩЕ: он мерит getBoundingClientRect
  // первого непоказанного пузыря, а тот стоял display: none и отдавал нули — условие никогда
  // не выполнялось. С этой правки непоказанная реплика держит высоту, такт ожил сам, и его
  // пришлось развести по вызовам: на свежем шаге он и задуман (увести прочитанное вверх), а в
  // подборщике забытых пузырей (revealSweep, щелчок внутри верстака) он бы дёргал колонку
  // ровно в тот момент, когда участник работает руками.
  function revealRun(host, done, clear) {
    if (revealTimer) { clearTimeout(revealTimer); revealTimer = null; }
    var q = [].slice.call(host.querySelectorAll('[data-reveal="1"]'));
    // ⚠ СНАЧАЛА ОСВОБОЖДАЕМ ЭКРАН, ПОТОМ ГОВОРИМ (правка владельца 09.08). Прежде
    // чем показать первую новую реплику, уводим прочитанное вверх: первый пузырь
    // встаёт примерно на трети экрана, под ним пусто, и разговор идёт сверху вниз
    // по чистому месту. Раньше каждая реплика появлялась у нижнего края и толкала
    // колонку — отсюда «рывками». Если содержимого выше мало, браузер упрёт
    // прокрутку в начало сам, и ничего не сдвинется.
    var sc0 = el('talkScroll');
    if (clear && sc0 && q.length) {
      var first = q[0];
      var ft = first.getBoundingClientRect().top - sc0.getBoundingClientRect().top;
      var want = Math.round(sc0.clientHeight * 0.3);
      if (ft - want > 4) sc0.scrollTop += (ft - want);
    }
    // ⚠ КОЛОНКА ЕДЕТ ЗА РЕПЛИКОЙ (правка владельца 07.08). В кофейне разговор длинный,
    // и новые пузыри появлялись НИЖЕ видимой части: участник читал пустой экран, пока
    // сам не прокрутит. Догоняем только вниз и только если реплика вышла за нижний
    // край — если человек сам ушёл читать выше, экран у него не отнимаем.
    var follow = function (n) {
      var sc = el('talkScroll');
      if (!sc) return;
      var pull = function () {
        var nb = n.getBoundingClientRect(), sb = sc.getBoundingClientRect();
        // ⚠ Не «лишь бы влезла», а В ЗОНУ ЧТЕНИЯ: под новой репликой остаётся пятая
        // часть колонки. Иначе она выскакивала ровно у нижнего края — там, где глаз
        // читать не привык, и разговор выглядел рваным (правка владельца 07.08).
        var pad = Math.max(28, Math.round(sc.clientHeight * 0.2));
        var below = nb.bottom - (sb.bottom - pad);
        if (below > 0) sc.scrollTop += below;
      };
      pull();
      // ⚠ Второй заход после анимации: пузырь въезжает со сдвигом на 6px и
      // раскрывается до своей высоты уже после первого замера — без этого прохода
      // последняя реплика оставалась на полстроки под краем (замер: до 59px).
      setTimeout(pull, 340);
    };
    var step = function () {
      var n = q.shift();
      if (!n) { revealTimer = null; if (done) done(); return; }
      n.removeAttribute('data-reveal');
      n.classList.add('is-in');
      if (n.dataset && n.dataset.rk) shownBubbles[n.dataset.rk] = 1;
      follow(n);
      revealTimer = setTimeout(step, revealPause(n));
    };
    // Первый пузырь без задержки: пустой экран в ожидании первой реплики читается
    // как «не загрузилось».
    step();
  }

  // ⚠ ПОДБОРЩИК ЗАБЫТЫХ ПУЗЫРЕЙ. Реплики внутри верстака помечаются к показу там же,
  // где рисуется сам верстак, — а верстак умеет перерисовывать себя сам, без общего
  // render(): выбор наиболее вероятного будущего, подтверждение списка, «ещё вариант».
  // В такой перерисовке новый пузырь получал метку, но запускать показ было некому, и
  // он оставался прозрачным навсегда. Все такие перерисовки идут от щелчка, поэтому
  // после каждого щелчка проверяем: если показ не идёт, а помеченные пузыри есть —
  // показываем их.
  function revealSweep() {
    if (revealTimer) return;
    var host = el('talkCurrent');
    if (!host || !host.querySelector('[data-reveal="1"]')) return;
    revealRun(host);
  }
  document.addEventListener('click', function () { setTimeout(revealSweep, 0); });

  // ── КРУЖОК С ЛИЦОМ СОБЕСЕДНИКА ──
  // Файл кладётся в platform/assets/faces/<id>.jpg (96×96, круг рисует CSS). Пока
  // файла нет, в кружке стоят инициалы — это не заглушка «на потом», а честный
  // вид: имя всё равно написано рядом. Соответствие «имя → файл и стиль» лежит в
  // scenes.js (S.faces), потому что это данные о героях, а не логика движка.
  function faceHtml(who) {
    if (!who) return '';
    var f = (S.faces && S.faces[who]) || null;
    // ⚠ ИНИЦИАЛЫ ТОЛЬКО ИЗ БУКВ (правка 19.08). Брался первый символ каждого слова
    // как есть, и при имени вроде «Т. Ким» в кружок попадала точка, а при пустой
    // подстановке — запятая: кружок выглядел сломанным, а не безымянным.
    var ini = who.replace(/[^\p{L}\s]/gu, ' ').split(/\s+/)
      .filter(Boolean).map(function (w) { return w.charAt(0); }).join('').slice(0, 2).toUpperCase();
    var cls = 'chat-face' + (f && f.mood ? ' is-' + f.mood : '');
    if (f && f.src) {
      return '<span class="' + cls + '" style="background-image:url(' + esc(f.src) + ')" aria-hidden="true"></span>';
    }
    return '<span class="' + cls + '" aria-hidden="true">' + esc(ini) + '</span>';
  }

  // Имя говорящего у реплики. Пустая строка значит «продолжает предыдущий»: так
  // авторски размечена, например, реплика «обращаясь к Дарье» — говорит тот же
  // Брагин. Прогон реплик держит это имя и передаёт следующей (см. prevWho ниже).
  function speechWho(act) { return subst((act && act.who) || ''); }

  function speechHtml(act, staged, keyPrefix, prevWho) {
    var out = '';
    var pre = keyPrefix || act.id || act.who || 'sp';
    // ⚠ ОДИН ГОЛОС — ОДНО ИМЯ (правка владельца 21.08). Реплики в сцене разбиты на
    // отдельные акты (у каждого своя ремарка, своё условие, свой ключ показа), и
    // каждый акт печатал имя и кружок заново: Брагин представлялся четыре раза за
    // один разговор. Имя ставим только там, где голос СМЕНИЛСЯ. Акт без who —
    // продолжение по определению.
    var who = speechWho(act);
    var cont = prevWho != null && (!who || who === prevWho);
    // Фильтр ДО перебора, а не внутри: имя говорящего и ремарка привязаны к первому
    // пузырю, и пропуск первого молча стирал бы подпись реплики.
    (act.bubbles || []).filter(bubbleShown).forEach(function (b, i) {
      // ⚠ ИМЯ ГОВОРЯЩЕГО ТОЖЕ ЧЕРЕЗ subst. С 14.08 на выходе из офиса участника
      // догоняет хозяин отказанной им заявки — кто именно, известно только в момент
      // отрисовки, поэтому в сцене стоит {whoName}. Для остальных реплик подстановок
      // в имени нет и subst здесь ничего не меняет.
      var name = (i === 0 && !cont) ? who : '';
      var actLine = i === 0 ? (b.act || act.act || '') : (b.act || '');
      // Уже показанный пузырь рисуется на месте и без анимации; новый ждёт очереди.
      var rk = pre + ':' + i;
      // Первый пузырь продолжения прижимается к предыдущей реплике: зазор такой же,
      // как между пузырями одного голоса (см. .chat.is-cont в таблице стилей).
      var cls = 'chat' + (i === 0 && cont ? ' is-cont' : '');
      var attr = '';
      if (staged) {
        cls += ' is-staged';
        if (shownBubbles[rk]) cls += ' is-in';
        else attr = ' data-reveal="1" data-rk="' + esc(rk) + '"';
      }
      // Ремарка — своей строкой курсивом ПОД именем (решение владельца 07.08): в
      // одну строку с именем она читалась как часть должности.
      out += '<div class="' + cls + '"' + attr + '><div class="chat-msg them"' + (act.who ? ' data-who="' + esc(subst(act.who)) + '"' : '') + '>' +
        // Подпись рисуется, только если в ней есть буквы: подстановка может вернуть
        // пустое или знак препинания, и тогда над репликой висел бы кружок с запятой.
        (/\p{L}/u.test(name) ? '<span class="chat-name">' + faceHtml(subst(act.who)) + esc(name) + '</span>' : '') +
        // ⚠ Ремарка рисуется и БЕЗ имени: у реплики «обращаясь к Дарье» говорящий тот
        // же, поэтому имени нет, а ремарка есть — и раньше она пропадала совсем.
        (i === 0 && act.note ? '<span class="chat-note">' + esc(act.note) + '</span>' : '') +
        (actLine ? '<div class="chat-act">' + esc(actLine) + '</div>' : '') +
        '<div class="chat-bubble">' + br(subst(b.text)) + '</div>' +
        '</div></div>';
    });
    return out;
  }

  // ⚠ ПОЛЯ ОТВЕТА РАСТУТ ПОД ТЕКСТ (решение владельца 19.08). Высота задавалась
  // атрибутом rows и была разной на разных шагах — от двух строк до девяти: на
  // одном экране рядом стояли поля двух разных размеров, а пустое поле в девять
  // строк занимало половину экрана обещанием. Теперь у всех одна стартовая высота
  // (три строки), дальше поле растёт ровно под то, что написано.
  // Слушатель ОДИН на документе: верстаки перерисовываются целиком на каждое
  // действие, и вешать обработчик на каждое поле значило бы вешать его заново.
  var AUTO_RE = /(^|\s)(win-input|mx-input)(\s|$)/;
  function autoGrow(ta) {
    if (!ta || ta.tagName !== 'TEXTAREA' || !AUTO_RE.test(ta.className)) return;
    if (ta.classList.contains('mx-input-thin')) return;   // однострочная опора
    // ⚠ НЕ МЕРЯЕМ СКРЫТОЕ ПОЛЕ И НЕ МЕРЯЕМ В КАДР ПОКАЗА (правка владельца 21.08).
    // Рабочая область на время монолога спрятана (.is-await → display:none), а поля
    // внутри верстака ждут своей очереди (.mx-ansbox.is-staged). У спрятанного узла
    // мерить нечего; хуже — у узла, ТОЛЬКО ЧТО показанного, браузер в том же кадре
    // отдаёт scrollHeight от прежней раскладки: пустое поле в три строки (81px)
    // мерилось как 188. Оттуда и брались «то три строки, то девять» — и прежний
    // пол 200px, которым эту разницу когда-то накрыли. Поэтому: пока поля нет на
    // экране, высоту держит rows, а замер откладывается на следующий кадр
    // (autoGrowSoon ниже, зовётся из openWork).
    if (!ta.offsetHeight) { ta.style.height = ''; return; }
    ta.style.height = 'auto';
    // ⚠ РАМКУ ПРИБАВЛЯЕМ ОБРАТНО. box-sizing: border-box, а scrollHeight рамок не
    // содержит — поле, выросшее под текст, выходило на 2px ниже соседнего, ещё не
    // тронутого: на экране с четырьмя полями подряд разница видна.
    ta.style.height = (ta.scrollHeight + (ta.offsetHeight - ta.clientHeight)) + 'px';
  }
  // ⚠ ПЛАВНО — ЭТО ПРОСЬБА, А НЕ ГАРАНТИЯ. behavior:'smooth' — анимация, и она не
  // выполняется, когда выполнять её незачем или нельзя: в невидимой вкладке (кадры
  // не идут), при снятой анимации в системе, и она отменяется любым следующим
  // распоряжением прокруткой — в том числе синхронным `scrollTop +=` ниже по коду.
  // Для красоты это неважно. Для подтяжки к кнопке «Ответить» — важно: если анимация
  // не состоялась, участник остаётся с вопросом на экране и без того, чем отвечать.
  // Замер 24.08, 1440×900, шаг «Чем нам придётся пожертвовать»: подтянуть нужно 173px
  // (поле показано на 7px, кнопка на 157px ниже дна колонки, 207px прокрутки не
  // использовано) — то есть цена невыполненной анимации здесь ровно та.
  // Рядом, у выравнивания по шапке сцены, зависимость от smooth уже снята с пометкой
  // «мгновенно, без smooth: плавная прокрутка на первом рендере не срабатывает» —
  // здесь она осталась. Поэтому: просим плавно, а через два кадра проверяем, и если
  // колонка не двинулась к цели — ставим жёстко.
  function scrollSoft(box, top) {
    if (typeof box.scrollTo !== 'function') { box.scrollTop = top; return; }
    var seen = box.scrollTop;
    try { box.scrollTo({ top: top, behavior: 'smooth' }); }
    catch (e) { box.scrollTop = top; return; }
    // Два замера: через два кадра (анимация не началась вовсе) и после того, как она
    // уже должна была кончиться (началась и была отменена). Оба раза сверяемся с тем,
    // что видели в прошлый раз: если колонку двигал КТО-ТО ЕЩЁ — участник колесом или
    // следующий шаг, — место у него не отнимаем и уходим. Это тот же принцип, что у
    // follow(): догоняем, но не перебиваем человека.
    var finish = function () {
      var at = box.scrollTop;
      if (Math.abs(at - top) <= 2) return;         // доехали
      if (Math.abs(at - seen) > 1) { seen = at; return; }  // едет или это не мы — не мешаем
      box.scrollTop = top;
    };
    if (window.requestAnimationFrame) {
      window.requestAnimationFrame(function () { window.requestAnimationFrame(finish); });
    } else setTimeout(finish, 32);
    setTimeout(finish, 480);
  }

  function autoGrowAll(root) {
    (root || document).querySelectorAll('textarea.win-input, textarea.mx-input')
      .forEach(autoGrow);
  }
  // Тот же обход, но следующим кадром: зовётся там, где поля только что показались,
  // и мерить их в этом же кадре нельзя (см. autoGrow).
  function autoGrowSoon(root) {
    if (window.requestAnimationFrame) window.requestAnimationFrame(function () { autoGrowAll(root); });
    else setTimeout(function () { autoGrowAll(root); }, 0);
  }
