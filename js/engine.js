  function applies(act) {
    // ⚠ `unless` — ТО ЖЕ УСЛОВИЕ НАОБОРОТ (правка 19.08). Понадобилось, чтобы
    // развести вопрос про плату на две реплики: перебравшему Агеев говорит про
    // превышение, уложившемуся — про состав решений. Отдельного условия «уложился»
    // сознательно НЕТ: два независимых условия рано или поздно разъедутся, и часть
    // участников осталась бы без вопроса или получила бы оба. Отрицание одного и
    // того же счёта разъехаться не может.
    if (act.unless) return !applies({ when: act.unless });
    if (!act.when) return true;
    if (act.when === 'overspend') {
      var t = listSums();
      // ⚠ Перебор считается по НОВОМУ списку (три решения + выбранные внутри вилки
      // числа), а не по прежнему totals() над picks: со маршрута v4.4.f на столе
      // лежат ещё и варианты участника, и их цену участник выбирает сам внутри
      // пределов. Старый totals() их не видел вовсе — ветка «чем платим» молчала
      // бы ровно там, где участник вышел за рамку своим вариантом.
      return t ? t.over : totals().over;
    }
    // ⚠ УСЛОВИЕ ОБМЕНА (правка 5.1). Реплика опирается на поступок участника: правление
    // настаивает на ОТКЛОНЁННОЙ им заявке. Если он не отклонил ничего, отказывать было не
    // от чего, и шаг не играется — иначе Агеев произносит фразу с дырами. Гейтом это
    // чинить нельзя: требование «отметьте хотя бы один отказ» сообщило бы участнику, что
    // от него ждут отказов, а наличие явных отказов и есть граница ПР-2 2→3.
    // Своё имя по смыслу, а не заимствованное у встречи на выходе: с правки 13.1 условия
    // разошлись — здесь любой отказ, там любой, КРОМЕ заявки правления.
    if (act.when === 'refused') return refusedIds().length > 0;
    // Отложена ли ТА заявка, с хозяином которой участник встретился (правка 13.2).
    // Отдельного условия «отклонена» нет намеренно: два независимых условия про одно и то
    // же разъедутся, а отрицание одного счёта — нет (то же основание, что у unless выше).
    if (act.when === 'refusedLater') {
      return window.imp.refusedOwnerIsLater(refusedSets(), listSums() || totals(), LIM);
    }
    if (act.when === 'severova') {
      // Встреча есть у каждого, кто хоть что-то отложил или отклонил (решение
      // владельца 14.08). Прежде условием был отказ ровно заявке №6, и окно было
      // условным — из-за чего его пришлось держать вне балла.
      // ⚠ УСЛОВИЕ ПРОЩЕ ВЫБОРА (правка 13.1): достаточно одной отклонённой, кроме
      // заявки правления. Считать полный выбор здесь нельзя — маршрут сказал бы
      // «шаг играется» там, где выбирать некого.
      return window.imp.refusedTalkIds(refusedSets(), listSums() || totals(), LIM).length > 0;
    }
    return true;
  }
  // Останавливающие акты: на них курсор стоит и ждёт участника. Реплики через
  // такой акт проскакивают — они рисуются как часть текущей сцены. Межсценовый
  // экран останавливающий: он и существует затем, чтобы день не переезжал из
  // разговора в разговор без единого вдоха (СПЕК §4.4).
  function isBlocking(act) {
    return act.kind === 'window' || act.kind === 'mechanic' || act.kind === 'case' || act.kind === 'interlude';
  }

  // Реплики, КОТОРЫМИ СЦЕНА ЗАКАНЧИВАЕТСЯ: после этого шага в сцене остались только
  // они, ни одного останавливающего акта. Такого случая раньше не было — прощание
  // Агеева висело полем `after` у верстака печати, — поэтому фиксация верстака
  // двигала день сразу, а отрисовка до этих реплик не доходила. Когда вопрос про
  // перебор переехал за утверждение (11.08), прощание стало отдельным завершающим
  // тактом и пропало с экрана в обеих ветках.
  function sceneTailSpeech(ix) {
    var out = [], sc = route[ix] && route[ix].sceneIx;
    for (var k = ix + 1; k < route.length; k++) {
      if (route[k].sceneIx !== sc) break;
      if (!applies(route[k].act)) continue;
      if (route[k].act.kind !== 'speech') return [];
      out.push(route[k].act);
    }
    return out;
  }

  function normalizeCursor() {
    while (state.cursor < route.length) {
      var st = route[state.cursor];
      if (applies(st.act) && isBlocking(st.act)) return;
      state.cursor++;
    }
  }

