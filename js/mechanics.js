  // С2 · ВАРИАНТЫ. Меряет ГА-1 (что компания может сделать) и ГА-2 (источник).
  // Приглашение множественности только механическое — кнопка «+ ещё вариант».
  // Словесного «если видите не один вариант» здесь нет: это элиситация границы.
  // ═════════════════════════════════════════════════════════════════════════
  M.variants = {
    // ⚠ ПОЛЯ «НАЗВАНИЕ» БОЛЬШЕ НЕТ (правка владельца 12.08). Оно просило придумать
    // ярлык прежде, чем сказана сама мысль, и на экране стояло первым — то есть
    // человек начинал с упаковки. `name` остаётся в состоянии пустой строкой: записи
    // до 12.08 его несут, и сводки читают оба поля.
    // picked === null — первый такт (веер). После «Ответить» становится true, и
    // открывается второй такт: какое из записанного основное и почему.
    init: function () { return { rays: [{ name: '', gist: '', from: '' }], picked: null, mainText: '', mainWhy: '' }; },
    gate: function (m, ctx) {
      if (ctx.isDemo) return '';
      if (m.picked == null) {
        return m.rays.some(function (r) { return String(r.gist).trim(); })
          ? '' : 'Нужен хотя бы один вариант с непустой сутью.';
      }
      if (!String(m.mainText).trim()) return 'Напишите вашу основную рекомендацию.';
      if (!String(m.mainWhy).trim()) return 'Скажите, почему она, а не то, что перечислили выше.';
      return '';
    },
    foot: function (m) {
      // Инфинитив, а не прошедшее время в мужском роде: см. scenes.js, правка 11.08.
      return { note: '', cta: (m && m.picked != null) ? 'Ответить →' : 'Ответить →' };
    },
    // Первый «Ответить» день НЕ двигает: он закрывает веер и открывает выбор.
    // Тот же приём, что у печати (M.seal.onCta): вернуть false значит «я
    // перерисовалась сама», день остаётся на этом шаге.
    onCta: function (m, ctx) {
      if (m.picked == null) { m.picked = true; ctx.save(); ctx.redraw(); return false; }
      return true;
    },
    locked: function (m) {
      var n = m.rays.filter(function (r) { return String((r.name || '') + r.gist).trim(); }).length;
      return '<b>' + n + '</b> ' + plural(n, 'вариант', 'варианта', 'вариантов') +
        ' <span class="bl-locked-hint">целиком — во вкладке «Мои ответы»</span>';
    },
    render: function (host, m, ctx) {
      // ── ВТОРОЙ ТАКТ: какое из записанного основное ──────────────────────────
      // Агеев «угадывает» ПЕРВЫЙ записанный вариант. Правило детерминировано, и это
      // то же обоснование, что в СПЕК §4.5а: случайность давала бы разным участникам
      // разную задачу и не воспроизводилась бы харнессом модели. Первый — потому что
      // с главного обычно и начинают, то есть догадка правдоподобна, а не техническая.
      // Второй такт: перечисленное показано только для сверки, править его уже нельзя —
      // веер сдан. Ниже два поля: сама рекомендация и почему она, а не эти.
      var drawMain = function () {
        var live = m.rays.filter(function (r) { return String(r.gist).trim(); });
        var h = ctx.speech(ctx.probe);
        if (live.length) {
          h += head(COPY.variants.sealed, '');
          live.forEach(function (r, i) {
            h += '<div class="mx-card mx-card-ro"><div class="mx-card-top"><span class="bl-n">' + (i + 1) + '</span></div>' +
              '<div class="mx-ray-gist">' + ctx.br(ctx.esc(r.gist)) + '</div></div>';
          });
        }
        h += answerBox(ctx, COPY.variants.main.label,
               { id: 'mxMT', f: 'mainText', ph: COPY.variants.main.ph, rows: 3, val: m.mainText }) +
             answerBox(ctx, COPY.variants.mainWhy.label,
               { id: 'mxMW', f: 'mainWhy', ph: COPY.variants.mainWhy.ph, rows: 3, val: m.mainWhy });
        host.innerHTML = h;
        var mt = host.querySelector('[data-f="mainText"]');
        if (mt) mt.addEventListener('input', function () { m.mainText = mt.value; ctx.save(); ctx.sync(); });
        var mw = host.querySelector('[data-f="mainWhy"]');
        if (mw) mw.addEventListener('input', function () { m.mainWhy = mw.value; ctx.save(); ctx.sync(); });
      };
      if (m.picked != null) { drawMain(); return; }
      var draw = function () {
        var h = head(COPY.variants.section, '<span class="mx-count">вариантов: ' + m.rays.length + '</span>');
        m.rays.forEach(function (r, i) {
          h += numbered(i + 1, '<div class="mx-card">' +
            field(ctx, { id: 'mxG' + i, f: 'gist', i: i, label: '', ph: COPY.variants.gist.label, val: r.gist }) +
            field(ctx, { id: 'mxF' + i, f: 'from', i: i, label: '', ph: COPY.variants.from.label, rows: 2, val: r.from }) +
            '<div class="mx-acts mx-acts-foot">' + (m.rays.length > 1 ? '<button type="button" class="s2-act" data-del="' + i + '">убрать</button>' : '') + '</div>' +
            '</div>');
        });
        h += '<button type="button" class="mx-add" data-add="1">+ ещё вариант</button>';
        host.innerHTML = h;
        host.querySelectorAll('[data-f]').forEach(function (el) {
          el.addEventListener('input', function () {
            m.rays[Number(el.dataset.i)][el.dataset.f] = el.value; ctx.save(); ctx.sync();
          });
        });
      };
      // один раз, снаружи draw() — см. пояснение в M.theses
      wireClick(host, function (e) {
        var a = e.target.getAttribute && e.target.getAttribute('data-del');
        if (a) {
          var ray = m.rays[Number(a)];
          if (!askDrop(ray && (String(ray.gist).trim() || String(ray.from).trim()))) return;
          m.rays.splice(Number(a), 1); ctx.save(); draw(); ctx.sync(); return;
        }
        if (e.target.getAttribute && e.target.getAttribute('data-add')) {
          m.rays.push({ gist: '', from: '' }); ctx.save(); draw(); ctx.sync();
        }
      });
      draw();
    }
  };

