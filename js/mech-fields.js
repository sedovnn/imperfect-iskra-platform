  // она была написана в engine.js, у двух остальных её не было вовсе.
  window.imp.winParts = {
    // Форма для модели: ключи — те же вопросы, что человек читает над полями.
    form: function (act) {
      var f = {};
      (act && act.parts || []).forEach(function (p) { f[p.q] = act.placeholder || 'ваш ответ'; });
      return f;
    },
    // Ответ модели → та же строка, которую сохраняет экран: вопрос, под ним ответ.
    toText: function (act, o) {
      return (act && act.parts || []).map(function (p) {
        var t = String((o && (o[p.q] || o[p.q.toLowerCase()])) || '').trim();
        return t ? p.q + '\n' + t : '';
      }).filter(Boolean).join('\n\n');
    },
    // Обратный разбор — по строкам-вопросам. Им экран раскладывает сохранённый ответ
    // назад по полям, когда участник возвращается на шаг.
    split: function (act, text) {
      var qs = (act && act.parts || []).map(function (p) { return p.q; });
      var out = qs.map(function () { return ''; });
      var at = -1, buf = [];
      var flush = function () { if (at >= 0) out[at] = buf.join('\n').trim(); buf = []; };
      String(text || '').split('\n').forEach(function (ln) {
        var ix = qs.indexOf(ln.trim());
        if (ix >= 0) { flush(); at = ix; return; }
        if (at >= 0) buf.push(ln);
      });
      flush();
      return out;
    }
  };

