/* НАДГРОБИЕ, а не сервис-воркер. PWA снята с публикации 2026-08-03: пока
   маршрут переписывается, вторая копия сайта в браузере вредит (при дрогнувшей
   сети отдаёт запас, и старую оболочку легко принять за текущее состояние), а
   пользы не даёт — на входе заглушка, день никто не проходит.

   Просто удалить файл нельзя. У всех, кто открыл сайт 3 августа, воркер уже
   зарегистрирован, и регистрация живёт в браузере, а не в репозитории: удалённый
   файл убрал бы обновление, но не саму регистрацию. Поэтому здесь оставлен
   воркер, который чистит кэши и снимает себя сам при первой же навигации.

   Рабочая сборка PWA лежит в бэкапе: docs/platform-pwa/ (там же README_pwa.md —
   когда возвращать и какие две правки сделать при возврате). При возврате этот
   файл заменяется настоящим воркером, и в нём поднимается VERSION. */

self.addEventListener('install', function () { self.skipWaiting(); });

self.addEventListener('activate', function (e) {
  e.waitUntil(
    caches.keys()
      .then(function (names) { return Promise.all(names.map(function (n) { return caches.delete(n); })); })
      .then(function () { return self.registration.unregister(); })
      .then(function () { return self.clients.matchAll({ type: 'window' }); })
      .then(function (clients) {
        // Перезагружаем открытые вкладки: они сейчас под управлением снятого
        // воркера, и без этого до закрытия вкладки продолжали бы получать его кэш.
        clients.forEach(function (c) { if (c.navigate) { try { c.navigate(c.url); } catch (err) {} } });
      })
  );
});

